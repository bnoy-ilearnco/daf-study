#!/usr/bin/env python3
"""Refresh shiurim.js with Rabbi Moshe Brown's Yevamos and Bechoros shiurim from Shas Illuminated.

Runs daily from .github/workflows/update-shiurim.yml. It rewrites shiurim.js only when the
list of shiurim actually changed, and it refuses to write a list that got shorter, so a
failed or partial fetch can never wipe shiurim off the site.
"""
import datetime
import json
import pathlib
import re
import sys
import time
import urllib.parse
import urllib.request

SPEAKER_ID = 27  # Rabbi Moshe Brown on shasilluminated.org
API = "https://www.shasilluminated.org/api/magidei-shiur/torah/{sid}/shiurim"
TRACTATES = {
    # key: (search name, first daf, last daf)
    "y": ("Yevamos", 2, 122),
    "b": ("Bechoros", 2, 61),
}
OUT = pathlib.Path(__file__).resolve().parent.parent / "shiurim.js"
FIELDS = ("d", "s", "len", "date", "note", "part", "url")

RE_C13 = re.compile(r"^(?:yevamos|bechoros)\s*0*(\d+)(?:\s*part\s*(\d+))?\s*-\s*cycle\s*13$", re.I)
RE_OLD = re.compile(r"^(?:YEVAMOS|Bechoros)(\d+)$")
RE_DY = re.compile(r"^(?:Yevamos|Bechoros)\s+(\d+)(?:\s*\(([^)]+)\))?$")
RE_RANGE = re.compile(r"^(\d+)[ab]?(?:-(\d+)[ab]?)?$")


def fetch_all(name):
    rows, page = [], 1
    while True:
        qs = urllib.parse.urlencode({
            "query": "{}", "limit": 100, "ascending": 1, "page": page,
            "byColumn": 1, "name": name, "topic_id": 0,
        })
        req = urllib.request.Request(
            API.format(sid=SPEAKER_ID) + "?" + qs,
            headers={"User-Agent": "Mozilla/5.0 (daf-study updater)", "Accept": "application/json"},
        )
        for attempt in range(3):
            try:
                with urllib.request.urlopen(req, timeout=60) as r:
                    data = json.load(r)
                break
            except Exception as e:  # noqa: BLE001
                if attempt == 2:
                    raise RuntimeError(f"Could not fetch {name} page {page}: {e}") from e
                time.sleep(5)
        batch = data.get("data") or []
        rows.extend(batch)
        if len(batch) < 100:
            return rows
        page += 1


def norm_len(s):
    return re.sub(r"^0(\d:)", r"\1", (s or "").strip())


def norm_date(s):
    return re.sub(r"^0", "", (s or "").strip())


def classify(row, first, last):
    """Return an entry dict, or None if the title doesn't match a known pattern."""
    name = (row.get("name") or "").strip()
    url = (row.get("url_download") or "").strip()
    if not url:
        return None
    e = {"len": norm_len(row.get("length")), "url": url}
    m = RE_C13.match(name)
    if m:
        e.update(d=[int(m.group(1))], s="c13")
        if m.group(2) and int(m.group(2)) > 1:
            e["part"] = int(m.group(2))
    elif RE_OLD.match(name):
        e.update(d=[int(RE_OLD.match(name).group(1))], s="old")
    elif RE_DY.match(name):
        m = RE_DY.match(name)
        date = norm_date(row.get("recorded"))
        year = date[-4:] if re.search(r"\d{4}$", date) else "?"
        dapim = [int(m.group(1))]
        if m.group(2):
            r = RE_RANGE.match(m.group(2).strip())
            if not r:
                return None
            lo = int(r.group(1))
            hi = int(r.group(2)) if r.group(2) else lo
            dapim = list(range(lo, hi + 1))
            e["note"] = "covers " + m.group(2).strip()
        e.update(d=dapim, s="dy" + year, date=date)
    else:
        return None
    e["d"] = [d for d in e["d"] if first <= d <= last]
    if not e["d"]:
        return None
    return {k: e[k] for k in FIELDS if k in e}


def current_data():
    if not OUT.exists():
        return None
    m = re.search(r"window\.SHIURIM = (\{.*\});", OUT.read_text(encoding="utf-8"), re.S)
    return json.loads(m.group(1)) if m else None


def main():
    new = {}
    for key, (name, first, last) in TRACTATES.items():
        rows = fetch_all(name)
        entries, skipped = {}, []
        for row in rows:
            e = classify(row, first, last)
            if e:
                entries[e["url"]] = e
            else:
                skipped.append(row.get("name"))
        new[key] = sorted(entries.values(), key=lambda e: e["url"])
        print(f"{name}: {len(rows)} fetched, {len(new[key])} kept, {len(skipped)} skipped {skipped[:10]}")

    old = current_data()
    if old is not None:
        for key in new:
            if len(new[key]) < len(old.get(key, [])):
                sys.exit(f"Refusing to shrink {key} from {len(old[key])} to {len(new[key])} shiurim; site left unchanged.")
        if old == new:
            print("No new shiurim.")
            return

    today = datetime.date.today().isoformat()
    body = json.dumps(new, ensure_ascii=False, separators=(",", ":"))
    OUT.write_text(
        "// Generated by tools/update_shiurim.py. Do not edit by hand.\n"
        f'window.SHIURIM_UPDATED = "{today}";\n'
        f"window.SHIURIM = {body};\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT.name}: " + ", ".join(f"{k}={len(v)}" for k, v in new.items()))


if __name__ == "__main__":
    main()
